#!/bin/sh

set -e -u

release_dir_name="$1"

echo '# Generated by the CI build for https://gitlab.cs.uni-duesseldorf.de/general/stups/camille - do not edit manually.'
echo 'RewriteEngine On'
# Redirect the "release" directory to the directory for the version number being published.
# For backwards compatibility reasons, also redirect the "nightly" directory to the latest release -
# older Rodin versions had the Camille nightly repository configured by default.
# (The real nightly repository for Camille is now called "develop".)
echo 'RewriteRule "^(?:release|nightly)(/.*)?$" "/rodin/camille/'"${release_dir_name}"'$1" [R=temp,L]'
